CREATE DATABASE IF NOT EXISTS Gestion_Biblioteca;
USE Gestion_Biblioteca;

CREATE TABLE Clientes (
    CLIENTE_ID VARCHAR(10) PRIMARY KEY,
    FIRST_NAME VARCHAR(50),
    LAST_NAME VARCHAR(50),
    CUSTOMER_EMAIL VARCHAR(100),
    CUSTOMER_ADDRESS VARCHAR(200)
);

CREATE TABLE Libros (
    BOOK_ID INT PRIMARY KEY,
    BOOK_TITLE VARCHAR(150),
    BOOK_AUTHOR VARCHAR(100)
);

CREATE TABLE Ordenes (
    ORDER_ID INT PRIMARY KEY,
    CLIENTE_ID VARCHAR(10),
    ORDER_DATE DATE,
    FOREIGN KEY (CLIENTE_ID) REFERENCES Clientes(CLIENTE_ID)
);

CREATE TABLE Detalle_Orden (
    ORDER_ID INT,
    BOOK_ID INT,
    QUANTITY INT,
    PRECIO_VENTA DECIMAL(10,2),
    PRIMARY KEY (ORDER_ID, BOOK_ID),
    FOREIGN KEY (ORDER_ID) REFERENCES Ordenes(ORDER_ID),
    FOREIGN KEY (BOOK_ID) REFERENCES Libros(BOOK_ID)
);


CREATE DATABASE IF NOT EXISTS Gestion_Vivero;
USE Gestion_Vivero;

CREATE TABLE Ubicaciones (
    LOCATION_CODE INT PRIMARY KEY,
    LOCATION_NAME VARCHAR(100)
);

CREATE TABLE Categorias_Suelo (
    SOIL_CATEGORY CHAR(1) PRIMARY KEY,
    SOIL_DESCRIPTION VARCHAR(100)
);

CREATE TABLE Plantas (
    PLANT_CODE INT PRIMARY KEY,
    PLANT_NAME VARCHAR(100),
    SOIL_CATEGORY CHAR(1),
    FOREIGN KEY (SOIL_CATEGORY) REFERENCES Categorias_Suelo(SOIL_CATEGORY)
);

CREATE TABLE Plantas_Ubicacion (
    LOCATION_CODE INT,
    PLANT_CODE INT,
    PRIMARY KEY (LOCATION_CODE, PLANT_CODE),
    FOREIGN KEY (LOCATION_CODE) REFERENCES Ubicaciones(LOCATION_CODE),
    FOREIGN KEY (PLANT_CODE) REFERENCES Plantas(PLANT_CODE)
);