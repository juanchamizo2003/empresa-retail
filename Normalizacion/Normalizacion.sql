CREATE DATABASE IF NOT EXISTS Gestion_Pedidos;
USE Gestion_Pedidos;

CREATE TABLE Clientes (
    ID_CLIENTE INT PRIMARY KEY,
    NOM_CLIENTE VARCHAR(100),
    ESTADO VARCHAR(10)
);

CREATE TABLE Items (
    NUM_ITEM INT PRIMARY KEY,
    DESC_ITEM VARCHAR(100),
    PRECIO DECIMAL(10,2)
);

CREATE TABLE Ordenes (
    ID_ORDEN INT PRIMARY KEY,
    FECHA VARCHAR(20), 
    ID_CLIENTE INT,
    FOREIGN KEY (ID_CLIENTE) REFERENCES Clientes(ID_CLIENTE)
);

CREATE TABLE Detalle_Orden (
    ID_ORDEN INT,
    NUM_ITEM INT,
    CANT INT,
    PRIMARY KEY (ID_ORDEN, NUM_ITEM),
    FOREIGN KEY (ID_ORDEN) REFERENCES Ordenes(ID_ORDEN),
    FOREIGN KEY (NUM_ITEM) REFERENCES Items(NUM_ITEM)
);

CREATE DATABASE IF NOT EXISTS Gestion_Peliculas_Alquiladas;
USE Gestion_Peliculas_Alquiladas;

CREATE TABLE Clientes (
    ID_CLIENTE INT PRIMARY KEY,
    FIRST_NAME VARCHAR(50),
    LAST_NAME VARCHAR(50),
    SALUTATION VARCHAR(10)
);

CREATE TABLE Direcciones (
    ID_PHYSICAL_ADDRESS VARCHAR(10) PRIMARY KEY,
    PHYSICAL_ADDRESS VARCHAR(200),
    ID_CLIENTE INT,
    FOREIGN KEY (ID_CLIENTE) REFERENCES Clientes(ID_CLIENTE)
);

CREATE TABLE Peliculas (
    ID_MOVIE VARCHAR(10) PRIMARY KEY,
    MOVIE_TITLE VARCHAR(150)
);

CREATE TABLE Renta_Peliculas (
    ID_RENTA INT AUTO_INCREMENT PRIMARY KEY, 
    ID_CLIENTE INT,
    ID_MOVIE VARCHAR(10),
    FOREIGN KEY (ID_CLIENTE) REFERENCES Clientes(ID_CLIENTE),
    FOREIGN KEY (ID_MOVIE) REFERENCES Peliculas(ID_MOVIE)
);


